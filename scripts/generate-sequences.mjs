// Generates src/data/maneuverSequences.json from a few COLA design choices per conjunction.
// Run: node scripts/generate-sequences.mjs
//
// Physics is deliberately first-order (linearised relative motion, circular orbit):
//   in-track burn dv  ->  da = 2 a dv / v
//   along-track drift ~= 3 * pi * da per revolution between burn and TCA
//   radial offset     ~= 2 * da
// Post-manoeuvre Pc rescales the seeded Pc by the Gaussian falloff along the
// dominant (in-track) covariance axis. Good enough for a deterministic demo.
import { readFileSync, writeFileSync } from 'node:fs'

const MU = 398600.4418 // km^3/s^2
const HOUR = 3600e3
const PC_FLOOR = 1e-10

const catalog = JSON.parse(readFileSync('src/data/catalog.json', 'utf8'))
const { events } = JSON.parse(readFileSync('src/data/conjunctions.json', 'utf8'))
const demoEpoch = Date.parse(catalog.demoEpoch)

const byId = (list, id) => {
  const hit = list.find((x) => x.id === id)
  if (!hit) throw new Error(`unknown id ${id}`)
  return hit
}

// Burn 1 is placed `revsBeforeTca` revolutions before TCA; Burn 2 half a revolution after
// TCA reverses it, restoring the nominal semi-major axis.
const designs = {
  'CJ-001': [
    { id: 'A', strategy: 'OPTIMAL_FUEL', name: 'Optimal Fuel Avoidance', dv: 0.08, revsBeforeTca: 2.5 },
    { id: 'B', strategy: 'RAPID_CLEARANCE', name: 'Rapid Clearance', dv: 0.45, revsBeforeTca: 0.5 },
    { id: 'C', strategy: 'BALANCED', name: 'Balanced Margin', dv: 0.18, revsBeforeTca: 1.5 },
  ],
  'CJ-002': [
    { id: 'A', strategy: 'OPTIMAL_FUEL', name: 'Optimal Fuel Avoidance', dv: 0.1, revsBeforeTca: 3.5 },
    { id: 'B', strategy: 'RAPID_CLEARANCE', name: 'Rapid Clearance', dv: 0.6, revsBeforeTca: 0.5 },
  ],
  'CJ-003': [
    { id: 'A', strategy: 'OPTIMAL_FUEL', name: 'Optimal Fuel Avoidance', dv: 0.12, revsBeforeTca: 3 },
    { id: 'B', strategy: 'RAPID_CLEARANCE', name: 'Rapid Clearance', dv: 0.9, revsBeforeTca: 0.5 },
  ],
}

const iso = (ms) => new Date(Math.round(ms / 1000) * 1000).toISOString().replace('.000Z', 'Z')
const round = (x, dp) => Number(x.toFixed(dp))

function buildSequence(event, design) {
  const primary = byId(catalog.objects, event.primaryId)
  const { smaKm } = primary.elements
  const { thrustN, massKg } = primary.envelope
  const vKmS = Math.sqrt(MU / smaKm)
  const periodMs = 2 * Math.PI * Math.sqrt(smaKm ** 3 / MU) * 1e3
  const tca = Date.parse(event.tca)

  const burnMs = ((design.dv * massKg) / thrustN) * 1e3
  const b1Start = tca - design.revsBeforeTca * periodMs
  const b1End = b1Start + burnMs
  const b2Start = tca + 0.5 * periodMs
  const b2End = b2Start + burnMs
  const postEnd = b2End + 24 * HOUR

  const daM = (2 * smaKm * 1e3 * design.dv) / (vKmS * 1e3)
  const driftM = 3 * Math.PI * daM * design.revsBeforeTca
  const m = event.missVector
  const post = { radialM: m.radialM + 2 * daM, inTrackM: m.inTrackM - driftM, crossTrackM: m.crossTrackM }
  const postMiss = Math.hypot(post.radialM, post.inTrackM, post.crossTrackM)
  const sigma = event.covariance.inTrackM
  const postPc = Math.max(
    PC_FLOOR,
    event.pc * Math.exp(-0.5 * (postMiss ** 2 - event.missDistanceM ** 2) / sigma ** 2),
  )

  const plusInTrack = { radial: 0, inTrack: 1, crossTrack: 0 }
  const minusInTrack = { radial: 0, inTrack: -1, crossTrack: 0 }
  const leadHours = round((tca - b1Start) / HOUR, 1)

  return {
    id: `SEQ-${event.id.slice(3)}-${design.id}`,
    conjunctionId: event.id,
    strategy: design.strategy,
    name: design.name,
    summary: `+${design.dv} m/s in-track ${leadHours} h before TCA opens ${(postMiss / 1e3).toFixed(1)} km; Burn 2 restores the nominal orbit.`,
    transferType: 'PHASING',
    totalDeltaVMps: round(2 * design.dv, 3),
    postMissDistanceM: Math.round(postMiss),
    postPc: Number(postPc.toPrecision(2)),
    steps: [
      { phase: 'COAST_MEAN_PRE', label: 'COAST (MEAN ELEM.)', start: iso(demoEpoch), end: iso(b1Start), propagator: 'SGP4', deltaVMps: 0, direction: null },
      { phase: 'BURN_1', label: 'BURN 1 (DEPARTURE)', start: iso(b1Start), end: iso(b1End), propagator: 'NUMERICAL', deltaVMps: design.dv, direction: plusInTrack },
      { phase: 'COAST_EPHEMERIS', label: 'COAST (EPHEMERIS)', start: iso(b1End), end: iso(b2Start), propagator: 'NUMERICAL', deltaVMps: 0, direction: null },
      { phase: 'BURN_2', label: 'BURN 2 (INSERTION)', start: iso(b2Start), end: iso(b2End), propagator: 'NUMERICAL', deltaVMps: design.dv, direction: minusInTrack },
      { phase: 'COAST_MEAN_POST', label: 'COAST (MEAN ELEM.)', start: iso(b2End), end: iso(postEnd), propagator: 'SGP4', deltaVMps: 0, direction: null },
    ],
  }
}

const sequences = Object.entries(designs).flatMap(([eventId, list]) =>
  list.map((d) => buildSequence(byId(events, eventId), d)),
)

const out = {
  note: 'Generated by scripts/generate-sequences.mjs. Do not edit by hand.',
  sequences,
}
writeFileSync('src/data/maneuverSequences.json', JSON.stringify(out, null, 2) + '\n')
console.log(`wrote ${sequences.length} sequences`)
